-- 0016 — حالة بونص غير محدود مستقلة عن سجل النقاط الرقمية
BEGIN;

ALTER TABLE public.members
  ADD COLUMN IF NOT EXISTS bonus_infinite BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.member_infinite_bonus_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL,
  member_name TEXT NOT NULL,
  member_email TEXT NOT NULL,
  enabled BOOLEAN NOT NULL,
  reason TEXT NOT NULL CHECK (pg_catalog.char_length(pg_catalog.btrim(reason)) BETWEEN 1 AND 500),
  actor_user_id UUID NOT NULL,
  actor_email TEXT NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp()
);

CREATE INDEX IF NOT EXISTS member_infinite_bonus_events_member_time_idx
  ON public.member_infinite_bonus_events (member_id, occurred_at DESC);

ALTER TABLE public.member_infinite_bonus_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.member_infinite_bonus_events FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.prevent_member_infinite_bonus_event_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'BONUS_AUDIT_IMMUTABLE: سجل تغييرات البونص غير قابل للتعديل أو الحذف.';
END;
$$;
REVOKE ALL ON FUNCTION public.prevent_member_infinite_bonus_event_mutation() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS member_infinite_bonus_events_immutable ON public.member_infinite_bonus_events;
CREATE TRIGGER member_infinite_bonus_events_immutable
  BEFORE UPDATE OR DELETE OR TRUNCATE ON public.member_infinite_bonus_events
  FOR EACH STATEMENT
  EXECUTE FUNCTION public.prevent_member_infinite_bonus_event_mutation();

COMMENT ON TABLE public.member_infinite_bonus_events IS
  'Append-only audit history for member infinite-bonus activation and cancellation.';

-- Ranking admins need read access to existing numeric bonus notes to render the ranking and member profile.
DROP POLICY IF EXISTS "Admin read notes by feature" ON public.notes;
CREATE POLICY "Admin read notes by feature" ON public.notes FOR SELECT TO authenticated
USING (
  public.has_admin_permission('dashboard')
  OR public.has_admin_permission('ranking')
  OR public.has_admin_permission('notes')
);

CREATE OR REPLACE FUNCTION public.guard_member_bonus_infinite_write()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF OLD.bonus_infinite IS DISTINCT FROM NEW.bonus_infinite
     AND pg_catalog.current_setting('wasla.member_bonus_rpc', true) IS DISTINCT FROM 'enabled' THEN
    RAISE EXCEPTION 'BONUS_RPC_REQUIRED: غيّر حالة البونص من شاشة تقييم العضو.';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.guard_member_bonus_infinite_write() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS members_bonus_infinite_rpc_only ON public.members;
CREATE TRIGGER members_bonus_infinite_rpc_only
  BEFORE UPDATE OF bonus_infinite ON public.members
  FOR EACH ROW
  EXECUTE FUNCTION public.guard_member_bonus_infinite_write();

CREATE OR REPLACE FUNCTION public.set_member_bonus_infinite(
  p_member_id BIGINT,
  p_enabled BOOLEAN,
  p_reason TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_enabled BOOLEAN;
  v_name TEXT;
  v_email TEXT;
  v_actor_email TEXT := COALESCE(NULLIF(pg_catalog.lower(pg_catalog.btrim(COALESCE(auth.jwt() ->> 'email', ''))), ''), auth.uid()::TEXT);
  v_reason TEXT := pg_catalog.btrim(COALESCE(p_reason, ''));
  v_write_token TEXT := pg_catalog.current_setting('wasla.member_bonus_rpc', true);
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_admin_permission('ranking') THEN
    RAISE EXCEPTION 'RANKING_PERMISSION_REQUIRED: يلزم صلاحية ترتيب الفريق لتعديل البونص غير المحدود.';
  END IF;
  IF p_member_id IS NULL OR p_member_id <= 0 OR p_enabled IS NULL THEN
    RAISE EXCEPTION 'INVALID_BONUS_REQUEST: بيانات تعديل البونص غير صالحة.';
  END IF;
  IF pg_catalog.char_length(v_reason) < 3 OR pg_catalog.char_length(v_reason) > 500 THEN
    RAISE EXCEPTION 'BONUS_REASON_REQUIRED: اكتب سبباً من 3 إلى 500 حرف.';
  END IF;

  SELECT m.bonus_infinite, m.full_name, m.email
    INTO v_enabled, v_name, v_email
  FROM public.members AS m
  WHERE m.id = p_member_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'MEMBER_NOT_FOUND: العضو غير موجود.';
  END IF;
  IF v_enabled = p_enabled THEN
    RAISE EXCEPTION 'BONUS_STATE_UNCHANGED: حالة البونص مطابقة للطلب بالفعل.';
  END IF;

  PERFORM pg_catalog.set_config('wasla.member_bonus_rpc', 'enabled', true);
  UPDATE public.members
  SET bonus_infinite = p_enabled
  WHERE id = p_member_id;
  PERFORM pg_catalog.set_config('wasla.member_bonus_rpc', COALESCE(v_write_token, ''), true);

  INSERT INTO public.member_infinite_bonus_events (
    member_id, member_name, member_email, enabled, reason, actor_user_id, actor_email
  ) VALUES (
    p_member_id, v_name, v_email, p_enabled, v_reason, auth.uid(), v_actor_email
  );

  RETURN p_enabled;
END;
$$;
REVOKE ALL ON FUNCTION public.set_member_bonus_infinite(BIGINT, BOOLEAN, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_member_bonus_infinite(BIGINT, BOOLEAN, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.get_member_bonus_infinite(
  p_member_id BIGINT,
  p_device_token TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_enabled BOOLEAN;
BEGIN
  PERFORM public.assert_member_device(p_member_id, p_device_token);

  SELECT m.bonus_infinite INTO v_enabled
  FROM public.members AS m
  WHERE m.id = p_member_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'MEMBER_NOT_FOUND: العضو غير موجود.';
  END IF;
  RETURN v_enabled;
END;
$$;
REVOKE ALL ON FUNCTION public.get_member_bonus_infinite(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_member_bonus_infinite(BIGINT, TEXT) TO anon, authenticated;

COMMIT;
