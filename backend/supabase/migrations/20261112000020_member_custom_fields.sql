    SELECT
      f.id,
      f.label,
      CASE
        WHEN f.field_type IN ('short_text', 'long_text', 'number', 'date', 'yes_no', 'select') THEN f.field_type
        ELSE 'short_text'
      END,
      COALESCE(f.options, '[]'::jsonb),
      LEFT(COALESCE(f.help_text, ''), 200),
      true,
      COALESCE(f.is_required, false),
      COALESCE(f.is_active, true),
      COALESCE(f.sort_order, 0),
      f.created_by,
      COALESCE(f.created_at, now()),
      COALESCE(f.updated_at, now())
    FROM public.member_info_fields AS f
    WHERE f.label NOT IN ('__PHANTOMS_ONBOARDING__')
    ON CONFLICT (id) DO NOTHING;

    PERFORM setval(
      pg_get_serial_sequence('public.member_custom_fields', 'id'),
      GREATEST(COALESCE((SELECT MAX(id) FROM public.member_custom_fields), 1), 1),
      true
    );
  END IF;
