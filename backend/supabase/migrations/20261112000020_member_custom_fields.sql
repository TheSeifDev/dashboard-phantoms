-- دالة إنشاء رابط دعوة جديد (للمشرفين فقط)
CREATE OR REPLACE FUNCTION public.create_member_invite(
  p_token TEXT,
  p_note TEXT DEFAULT '',
  p_expires_in_hours INT DEFAULT 168
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_hash TEXT;
  v_hours INT := LEAST(GREATEST(COALESCE(p_expires_in_hours, 168), 1), 2160);
  v_row public.member_registration_invites;
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_admin_permission('members') THEN
    RAISE EXCEPTION 'MEMBERS_PERMISSION_REQUIRED: يلزم صلاحية إدارة الأعضاء لإنشاء رابط دعوة.';
  END IF;
  IF p_token IS NULL OR pg_catalog.char_length(pg_catalog.btrim(p_token)) < 32 OR pg_catalog.char_length(p_token) > 512 THEN
    RAISE EXCEPTION 'INVALID_INVITE_TOKEN: رمز الدعوة غير صالح.';
  END IF;

  v_hash := pg_catalog.encode(
    extensions.digest(pg_catalog.convert_to(pg_catalog.btrim(p_token), 'UTF8'), 'sha256'),
    'hex'
  );

  INSERT INTO public.member_registration_invites (token_hash, note, expires_at, created_by)
  VALUES (v_hash, pg_catalog.left(pg_catalog.btrim(COALESCE(p_note, '')), 200), pg_catalog.now() + pg_catalog.make_interval(hours => v_hours), auth.uid())
  RETURNING * INTO v_row;

  RETURN jsonb_build_object(
    'id', v_row.id,
    'note', v_row.note,
    'expires_at', v_row.expires_at,
    'created_at', v_row.created_at
  );
END;
$$;
REVOKE ALL ON FUNCTION public.create_member_invite(TEXT, TEXT, INT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_member_invite(TEXT, TEXT, INT) TO authenticated;

-- دالة فحص رابط الدعوة وجلب الحقول المخصصة للعضو الجديد (متاحة عبر الرابط المحمي)
CREATE OR REPLACE FUNCTION public.get_member_invite_context(p_token TEXT)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_hash TEXT;
  v_inv public.member_registration_invites;
  v_fields JSONB;
BEGIN
  IF p_token IS NULL OR pg_catalog.char_length(pg_catalog.btrim(p_token)) < 32 OR pg_catalog.char_length(p_token) > 512 THEN
    RETURN jsonb_build_object('valid', false, 'reason', 'INVALID_TOKEN');
  END IF;

  v_hash := pg_catalog.encode(
    extensions.digest(pg_catalog.convert_to(pg_catalog.btrim(p_token), 'UTF8'), 'sha256'),
    'hex'
  );

  SELECT * INTO v_inv
  FROM public.member_registration_invites AS i
  WHERE i.token_hash = v_hash
  LIMIT 1;

  IF v_inv.id IS NULL OR v_inv.is_revoked OR v_inv.used_at IS NOT NULL OR v_inv.expires_at <= pg_catalog.now() THEN
    RETURN jsonb_build_object('valid', false, 'reason', 'EXPIRED_OR_USED');
  END IF;

  SELECT COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'id', f.id,
        'label', f.label,
        'field_type', f.field_type,
        'options', f.options,
        'placeholder', f.placeholder,
        'show_in_card', f.show_in_card,
        'is_required', f.is_required,
        'sort_order', f.sort_order
      ) ORDER BY f.sort_order, f.id
    ),
    '[]'::jsonb
  )
  INTO v_fields
  FROM public.member_custom_fields AS f
  WHERE f.is_active;

  RETURN jsonb_build_object(
    'valid', true,
    'note', v_inv.note,
    'expires_at', v_inv.expires_at,
    'custom_fields', v_fields
  );
END;
$$;
REVOKE ALL ON FUNCTION public.get_member_invite_context(TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_member_invite_context(TEXT) TO anon, authenticated;

-- دالة تسجيل بيانات العضو الجديد عبر رابط الدعوة وقفل الرابط ذرياً
CREATE OR REPLACE FUNCTION public.submit_member_registration_invite(p_token TEXT, p_payload JSONB)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_hash TEXT;
  v_inv public.member_registration_invites;
  v_full_name TEXT;
  v_email TEXT;
  v_phone TEXT;
  v_residence TEXT;
  v_work_conditions TEXT;
  v_device TEXT;
  v_gender TEXT;
  v_bio TEXT;
  v_can_go BOOLEAN;
  v_custom JSONB;
  v_member_id BIGINT;
BEGIN
  IF p_token IS NULL OR pg_catalog.char_length(pg_catalog.btrim(p_token)) < 32 OR pg_catalog.char_length(p_token) > 512 THEN
    RAISE EXCEPTION 'INVALID_OR_EXPIRED_INVITE: رابط التسجيل غير صالح أو انتهت صلاحيته.';
  END IF;

  IF p_payload IS NULL OR jsonb_typeof(p_payload) <> 'object' THEN
    RAISE EXCEPTION 'INVALID_PAYLOAD: البيانات المدخلة غير صالحة.';
  END IF;

  v_hash := pg_catalog.encode(
    extensions.digest(pg_catalog.convert_to(pg_catalog.btrim(p_token), 'UTF8'), 'sha256'),
    'hex'
  );

  SELECT * INTO v_inv
  FROM public.member_registration_invites AS i
  WHERE i.token_hash = v_hash
  FOR UPDATE;

  IF v_inv.id IS NULL OR v_inv.is_revoked OR v_inv.used_at IS NOT NULL OR v_inv.expires_at <= pg_catalog.now() THEN
    RAISE EXCEPTION 'INVALID_OR_EXPIRED_INVITE: هذا الرابط تم استخدامه بالفعل أو انتهت صلاحيته.';
  END IF;

  v_full_name := pg_catalog.btrim(COALESCE(p_payload ->> 'full_name', ''));
  v_email := pg_catalog.lower(pg_catalog.btrim(COALESCE(p_payload ->> 'email', '')));
  v_phone := NULLIF(pg_catalog.btrim(COALESCE(p_payload ->> 'phone', '')), '');
  v_residence := NULLIF(pg_catalog.btrim(COALESCE(p_payload ->> 'residence', '')), '');
  v_work_conditions := NULLIF(pg_catalog.btrim(COALESCE(p_payload ->> 'work_conditions', '')), '');
  v_device := COALESCE(NULLIF(pg_catalog.btrim(COALESCE(p_payload ->> 'device', '')), ''), 'لابتوب');
  v_gender := NULLIF(pg_catalog.btrim(COALESCE(p_payload ->> 'gender', '')), '');
  v_bio := NULLIF(pg_catalog.btrim(COALESCE(p_payload ->> 'bio', '')), '');
  v_can_go := COALESCE((p_payload -> 'can_go_alexandria')::boolean, false);
  v_custom := CASE
    WHEN jsonb_typeof(p_payload -> 'custom_fields') = 'object' THEN p_payload -> 'custom_fields'
    ELSE '{}'::jsonb
  END;

  IF pg_catalog.char_length(v_full_name) < 2 OR pg_catalog.char_length(v_full_name) > 120 THEN
    RAISE EXCEPTION 'INVALID_NAME: يرجى كتابة الاسم الكامل بشكل صحيح.';
  END IF;

  IF v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' OR pg_catalog.char_length(v_email) > 254 THEN
    RAISE EXCEPTION 'INVALID_EMAIL: يرجى كتابة بريد إلكتروني صحيح.';
  END IF;

  IF EXISTS (SELECT 1 FROM public.members AS m WHERE pg_catalog.lower(m.email) = v_email) THEN
    RAISE EXCEPTION 'EMAIL_ALREADY_EXISTS: البريد الإلكتروني ده مسجّل بالفعل في النظام.';
  END IF;

  INSERT INTO public.members (
    full_name, email, phone, residence, work_conditions, device, gender, bio,
    can_go_alexandria, work_status, completion_rank, custom_fields
  )
  VALUES (
    v_full_name, v_email, v_phone, v_residence, v_work_conditions, v_device, v_gender, v_bio,
    v_can_go, 'active', 0, v_custom
  )
  RETURNING id INTO v_member_id;

  UPDATE public.member_registration_invites
  SET used_at = pg_catalog.now(),
      registered_member_id = v_member_id
  WHERE id = v_inv.id;

  RETURN jsonb_build_object(
    'member_id', v_member_id,
    'full_name', v_full_name,
    'email', v_email
  );
END;
$$;
REVOKE ALL ON FUNCTION public.submit_member_registration_invite(TEXT, JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_member_registration_invite(TEXT, JSONB) TO anon, authenticated;

