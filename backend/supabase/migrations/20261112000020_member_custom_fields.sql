DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'member_info_fields'
  ) THEN
    INSERT INTO public.member_custom_fields (
      id, label, field_type, options, placeholder, show_in_card, is_required, is_active, sort_order, created_by, created_at, updated_at
