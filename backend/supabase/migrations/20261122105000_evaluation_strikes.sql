-- 20261122105000 — تحذيرات الأعضاء (Strikes) وخصم النجوم
-- كل عضو عنده ٣ تحذيرات كحد أقصى؛ التحذير الثالث معناه إن المالك لازم يطرده
-- من الفريق بالكامل. التحذير نفسه بيتسجل كتقييم (kind = 'strike') عشان يظهر
-- للعضو في بوابته، وبيتسجل كمان في member_strikes عشان العدّ والحد الأقصى.
BEGIN;

ALTER TABLE public.member_evaluations
  ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'stars';
ALTER TABLE public.member_evaluations
  DROP CONSTRAINT IF EXISTS member_evaluations_kind_check;
ALTER TABLE public.member_evaluations
  ADD CONSTRAINT member_evaluations_kind_check CHECK (kind IN ('stars', 'minus', 'strike'));
ALTER TABLE public.member_evaluations
  DROP CONSTRAINT IF EXISTS member_evaluations_strike_points_check;
ALTER TABLE public.member_evaluations
  ADD CONSTRAINT member_evaluations_strike_points_check CHECK (kind <> 'strike' OR points = 0);

CREATE TABLE IF NOT EXISTS public.member_strikes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL REFERENCES public.members (id) ON DELETE CASCADE,
  evaluation_id BIGINT REFERENCES public.member_evaluations (id) ON DELETE SET NULL,
  reason TEXT NOT NULL CHECK (pg_catalog.char_length(pg_catalog.btrim(reason)) BETWEEN 1 AND 500),
  issued_by UUID REFERENCES auth.users (id) ON DELETE SET NULL,
  issued_by_name TEXT CHECK (issued_by_name IS NULL OR pg_catalog.char_length(pg_catalog.btrim(issued_by_name)) BETWEEN 1 AND 120),
  created_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.now()
);
CREATE INDEX IF NOT EXISTS member_strikes_member_idx
  ON public.member_strikes (member_id, created_at DESC);
ALTER TABLE public.member_strikes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.member_strikes FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.member_strikes TO authenticated;
DROP POLICY IF EXISTS member_strikes_admin_read ON public.member_strikes;
CREATE POLICY member_strikes_admin_read ON public.member_strikes
  FOR SELECT TO authenticated
  USING (public.is_admin());

-- حد التحذيرات لكل عضو: ٣. الدالة بتقرأه عشان الواجهة والـ RPC يتفقوا.
CREATE OR REPLACE FUNCTION public.member_strike_limit()
RETURNS INTEGER LANGUAGE sql IMMUTABLE AS $$ SELECT 3 $$;
REVOKE ALL ON FUNCTION public.member_strike_limit() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.member_strike_limit() TO authenticated;

-- إصدار تحذير: بيسجل التقييم + التحذير في نفس المعاملة، وبيمنع الرابع.
CREATE OR REPLACE FUNCTION public.admin_issue_strike(
  p_member_id BIGINT,
  p_title TEXT,
  p_feedback TEXT,
  p_author TEXT DEFAULT NULL
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_count INTEGER;
  v_evaluation_id BIGINT;
  v_strike_id BIGINT;
  v_limit CONSTANT INTEGER := 3;
  v_title TEXT := pg_catalog.btrim(COALESCE(p_title, 'تحذير رسمي'));
  v_feedback TEXT := pg_catalog.btrim(COALESCE(p_feedback, ''));
  v_author TEXT := pg_catalog.btrim(COALESCE(NULLIF(p_author, ''), 'إدارة PHANTOMS'));
BEGIN
  IF NOT (public.is_owner() OR public.has_admin_permission('ranking')) THEN
    RAISE EXCEPTION 'UNAUTHORIZED';
  END IF;
  IF p_member_id IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.members AS m WHERE m.id = p_member_id AND COALESCE(m.work_status, '') = 'active'
  ) THEN
    RAISE EXCEPTION 'MEMBER_NOT_ACTIVE';
  END IF;
  IF pg_catalog.char_length(v_title) NOT BETWEEN 1 AND 200 THEN RAISE EXCEPTION 'INVALID_TITLE'; END IF;
  IF pg_catalog.char_length(v_feedback) NOT BETWEEN 1 AND 3000 THEN RAISE EXCEPTION 'INVALID_FEEDBACK'; END IF;
  IF pg_catalog.char_length(v_author) NOT BETWEEN 1 AND 120 THEN RAISE EXCEPTION 'INVALID_AUTHOR'; END IF;

  -- Serialize per member so two concurrent warnings can never exceed the limit.
  PERFORM pg_catalog.pg_advisory_xact_lock(p_member_id);

  SELECT count(*)::INTEGER INTO v_count FROM public.member_strikes AS s WHERE s.member_id = p_member_id;
  IF v_count >= v_limit THEN RAISE EXCEPTION 'STRIKE_LIMIT_REACHED'; END IF;

  INSERT INTO public.member_evaluations (member_id, title, grade, kind, points, feedback, evaluator_name, created_by)
  VALUES (p_member_id, v_title, 'warning', 'strike', 0, v_feedback, v_author, auth.uid())
  RETURNING id INTO v_evaluation_id;

  INSERT INTO public.member_strikes (member_id, evaluation_id, reason, issued_by, issued_by_name)
  VALUES (p_member_id, v_evaluation_id, v_feedback, auth.uid(), v_author)
  RETURNING id INTO v_strike_id;

  RETURN pg_catalog.jsonb_build_object(
    'strike_id', v_strike_id,
    'evaluation_id', v_evaluation_id,
    'member_id', p_member_id,
    'strikes', v_count + 1,
    'limit', v_limit,
    'expulsion_required', (v_count + 1) >= v_limit
  );
END;
$$;
REVOKE ALL ON FUNCTION public.admin_issue_strike(BIGINT, TEXT, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_issue_strike(BIGINT, TEXT, TEXT, TEXT) TO authenticated;

-- طرد العضو من الفريق بالكامل (المالك فقط): إيقاف العضو، إزالة عضويات الفرق،
-- وإلغاء ربط الدخول والجلسات عشان ما يقدرش يدخل البوابة تاني.
CREATE OR REPLACE FUNCTION public.owner_expel_member(p_member_id BIGINT, p_reason TEXT DEFAULT NULL)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_email TEXT;
  v_owner_email TEXT;
BEGIN
  IF NOT public.is_owner() THEN RAISE EXCEPTION 'OWNER_ONLY'; END IF;
  SELECT pg_catalog.lower(pg_catalog.btrim(m.email)) INTO v_email FROM public.members AS m WHERE m.id = p_member_id;
  IF v_email IS NULL THEN RAISE EXCEPTION 'MEMBER_NOT_FOUND'; END IF;
  SELECT pg_catalog.lower(pg_catalog.btrim(u.email)) INTO v_owner_email FROM auth.users AS u WHERE u.id = auth.uid();
  IF v_owner_email IS NOT NULL AND v_owner_email = v_email THEN RAISE EXCEPTION 'CANNOT_EXPEL_OWNER'; END IF;

  UPDATE public.members SET work_status = 'inactive' WHERE id = p_member_id;
  UPDATE public.team_memberships
  SET status = 'removed', updated_at = pg_catalog.now()
  WHERE member_id = p_member_id AND status <> 'removed';
  DELETE FROM public.member_device_sessions WHERE member_id = p_member_id;
  DELETE FROM public.member_auth_bindings WHERE member_id = p_member_id;
  DELETE FROM public.member_password_invitations
  WHERE member_id = p_member_id AND status IN ('reserved', 'review_required');

  RETURN pg_catalog.jsonb_build_object(
    'member_id', p_member_id,
    'expelled', true,
    'strikes', (SELECT count(*)::INTEGER FROM public.member_strikes AS s WHERE s.member_id = p_member_id),
    'reason', NULLIF(pg_catalog.btrim(COALESCE(p_reason, '')), '')
  );
END;
$$;
REVOKE ALL ON FUNCTION public.owner_expel_member(BIGINT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.owner_expel_member(BIGINT, TEXT) TO authenticated;

-- العضو بيشوف تحذيراته هو بس (من غير أي بيانات عن غيره).
CREATE OR REPLACE FUNCTION public.member_my_strikes()
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_access JSONB;
  v_member_id BIGINT;
BEGIN
  v_access := public.get_member_password_access();
  IF v_access IS NULL OR NOT (v_access ? 'member_id') THEN RAISE EXCEPTION 'UNAUTHORIZED'; END IF;
  v_member_id := (v_access ->> 'member_id')::BIGINT;
  RETURN pg_catalog.jsonb_build_object(
    'limit', 3,
    'strikes', COALESCE((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
        'id', s.id,
        'reason', s.reason,
        'created_at', s.created_at,
        'issued_by_name', s.issued_by_name
      ) ORDER BY s.created_at DESC)
      FROM public.member_strikes AS s
      WHERE s.member_id = v_member_id
    ), '[]'::JSONB)
  );
END;
$$;
REVOKE ALL ON FUNCTION public.member_my_strikes() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.member_my_strikes() TO authenticated;

COMMIT;
