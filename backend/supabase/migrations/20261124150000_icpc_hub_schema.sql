-- ICPC Hub — schema foundation.
-- كل الوصول بيمر عبر RPCs في 20261124150100_icpc_hub_api.sql، والجداول دي مقفولة بالكامل
-- على anon/authenticated بنفس أسلوب جداول التلجرام.

CREATE TABLE IF NOT EXISTS public.icpc_roles (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('coach', 'captain', 'member')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.icpc_topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title_ar TEXT NOT NULL,
    title_en TEXT NOT NULL,
    stage SMALLINT NOT NULL CHECK (stage BETWEEN 1 AND 7),
    difficulty TEXT NOT NULL DEFAULT 'medium' CHECK (difficulty IN ('easy', 'medium', 'hard')),
    description TEXT,
    prerequisites TEXT[] NOT NULL DEFAULT '{}',
    resources JSONB NOT NULL DEFAULT '[]'::jsonb,
    position INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_icpc_topics_stage ON public.icpc_topics (stage, position);

CREATE TABLE IF NOT EXISTS public.icpc_topic_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    topic_id BIGINT NOT NULL REFERENCES public.icpc_topics(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'learning', 'done')),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE (user_id, topic_id)
);

CREATE INDEX IF NOT EXISTS idx_icpc_topic_progress_user ON public.icpc_topic_progress (user_id);

CREATE TABLE IF NOT EXISTS public.icpc_platform_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'codechef', 'atcoder', 'cses', 'other')),
    handle TEXT NOT NULL,
    current_rating INT CHECK (current_rating IS NULL OR current_rating >= 0),
    peak_rating INT CHECK (peak_rating IS NULL OR peak_rating >= 0),
    last_sync_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE (user_id, platform)
);

CREATE TABLE IF NOT EXISTS public.icpc_rating_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES public.icpc_platform_accounts(id) ON DELETE CASCADE,
    contest_name TEXT NOT NULL,
    rating INT NOT NULL CHECK (rating >= 0),
    delta INT NOT NULL DEFAULT 0,
    rated_at DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE (account_id, contest_name, rated_at)
);

CREATE INDEX IF NOT EXISTS idx_icpc_rating_history_account ON public.icpc_rating_history (account_id, rated_at);

CREATE TABLE IF NOT EXISTS public.icpc_problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    url TEXT,
    platform TEXT NOT NULL DEFAULT 'codeforces' CHECK (platform IN ('codeforces', 'codechef', 'atcoder', 'cses', 'other')),
    external_id TEXT,
    difficulty TEXT NOT NULL DEFAULT 'medium' CHECK (difficulty IN ('easy', 'medium', 'hard', 'expert')),
    topics TEXT[] NOT NULL DEFAULT '{}',
    description TEXT,
    editorial_url TEXT,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_icpc_problems_platform ON public.icpc_problems (platform, difficulty);

CREATE TABLE IF NOT EXISTS public.icpc_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES public.icpc_problems(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'solving', 'solved', 'upsolving', 'revisit')),
    attempts INT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    notes TEXT,
    due_date DATE,
    solved_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE (problem_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_icpc_assignments_user ON public.icpc_assignments (user_id, status);
CREATE INDEX IF NOT EXISTS idx_icpc_assignments_solved ON public.icpc_assignments (solved_at);

CREATE TABLE IF NOT EXISTS public.icpc_contests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    platform TEXT NOT NULL DEFAULT 'internal' CHECK (platform IN ('codeforces', 'codechef', 'atcoder', 'cses', 'internal', 'other')),
    kind TEXT NOT NULL DEFAULT 'internal' CHECK (kind IN ('individual', 'virtual', 'internal')),
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INT NOT NULL DEFAULT 300 CHECK (duration_minutes BETWEEN 15 AND 1440),
    visibility TEXT NOT NULL DEFAULT 'team' CHECK (visibility IN ('team', 'admins')),
    status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('draft', 'scheduled', 'running', 'finished')),
    scoring JSONB NOT NULL DEFAULT '{"penalty_minutes": 20, "points_per_problem": 1}'::jsonb,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_icpc_contests_starts ON public.icpc_contests (starts_at DESC);

CREATE TABLE IF NOT EXISTS public.icpc_contest_problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id BIGINT NOT NULL REFERENCES public.icpc_contests(id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL REFERENCES public.icpc_problems(id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    points INT NOT NULL DEFAULT 1 CHECK (points > 0),
    UNIQUE (contest_id, problem_id)
);

CREATE TABLE IF NOT EXISTS public.icpc_contest_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id BIGINT NOT NULL REFERENCES public.icpc_contests(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    team_name TEXT,
    solved INT NOT NULL DEFAULT 0 CHECK (solved >= 0),
    penalty INT NOT NULL DEFAULT 0 CHECK (penalty >= 0),
    rank INT CHECK (rank IS NULL OR rank > 0),
    rating_delta INT,
    score NUMERIC(10, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE (contest_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.icpc_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'training' CHECK (kind IN ('training', 'mock', 'upsolving', 'sharing', 'deadline')),
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INT NOT NULL DEFAULT 90 CHECK (duration_minutes BETWEEN 15 AND 600),
    location TEXT,
    url TEXT,
    topic TEXT,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_icpc_sessions_starts ON public.icpc_sessions (starts_at);

CREATE TABLE IF NOT EXISTS public.icpc_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'algorithms' CHECK (category IN ('algorithms', 'data-structures', 'templates', 'complexity', 'techniques', 'editorials', 'lessons', 'team-notes')),
    tags TEXT[] NOT NULL DEFAULT '{}',
    content_md TEXT NOT NULL DEFAULT '',
    links JSONB NOT NULL DEFAULT '[]'::jsonb,
    author_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'pending')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_icpc_notes_category ON public.icpc_notes (category, created_at DESC);

-- الأمان: مفيش أي وصول مباشر. كل حاجة عبر RPCs بتتحقق من الهوية والصلاحية.
DO $$
DECLARE
    v_table TEXT;
BEGIN
    FOREACH v_table IN ARRAY ARRAY[
        'icpc_roles', 'icpc_topics', 'icpc_topic_progress', 'icpc_platform_accounts',
        'icpc_rating_history', 'icpc_problems', 'icpc_assignments', 'icpc_contests',
        'icpc_contest_problems', 'icpc_contest_participants', 'icpc_sessions', 'icpc_notes'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', v_table);
        EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', v_table);
        -- icpc_roles مالهاش identity column، فالسيكوينس مش موجودة أصلًا.
        IF to_regclass(format('public.%I_id_seq', v_table)) IS NOT NULL THEN
            EXECUTE format('REVOKE ALL ON SEQUENCE public.%I_id_seq FROM anon, authenticated', v_table);
        END IF;
    END LOOP;
END $$;

