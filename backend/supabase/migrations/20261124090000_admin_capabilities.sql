-- 4) بيانات وصول الإدارة (نسخة web_projects الكاملة + نافذة المالك المؤقتة) --
CREATE OR REPLACE FUNCTION public.get_admin_access()
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_email TEXT;
  v_role TEXT;
  v_permissions JSONB;
  v_all_permissions CONSTANT JSONB :=
    '{"dashboard":true,"members":true,"tasks":true,"ranking":true,"notes":true,"announcements":true,"whatsapp":true,"ai_assistant":true,"web_projects":true}'::jsonb;
  v_teams JSONB := '[]'::jsonb;
  v_owner_until TIMESTAMPTZ;
BEGIN
  IF v_user_id IS NULL THEN
    RETURN jsonb_build_object('is_admin', false, 'is_owner', false, 'is_team_admin', false,
      'role', NULL, 'email', NULL, 'permissions', '{}'::jsonb, 'teams', '[]'::jsonb);
  END IF;
  SELECT u.email INTO v_email FROM auth.users AS u WHERE u.id = v_user_id;
  SELECT a.role, a.permissions INTO v_role, v_permissions
  FROM public.admin_accounts AS a WHERE a.user_id = v_user_id;
  IF v_role = 'owner' THEN
    v_permissions := v_all_permissions;
  ELSIF v_role = 'admin' THEN
    v_permissions := COALESCE(v_permissions, '{}'::jsonb) ||
      jsonb_build_object('web_projects', COALESCE((v_permissions ->> 'web_projects')::boolean, false));
  END IF;
  IF v_role IN ('owner', 'admin') THEN
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
      'team_id', t.id, 'slug', t.slug, 'name', t.name, 'role', NULL, 'permissions', v_permissions
    ) ORDER BY t.name), '[]'::jsonb)
    INTO v_teams FROM public.teams AS t WHERE t.is_active;
  ELSE
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
      'team_id', t.id, 'slug', t.slug, 'name', t.name, 'role', a.role, 'permissions', a.permissions
    ) ORDER BY t.name), '[]'::jsonb)
    INTO v_teams
    FROM public.team_admin_assignments AS a
    JOIN public.teams AS t ON t.id = a.team_id AND t.is_active
    JOIN auth.users AS u ON u.id = a.user_id AND u.deleted_at IS NULL
      AND (u.banned_until IS NULL OR u.banned_until <= now())
    WHERE a.user_id = v_user_id;
  END IF;
  -- نافذة صلاحيات المالك المؤقتة (منحة full_owner) — بتظهر للمشرف بدون تغيير دوره.
  SELECT max(g.expires_at) INTO v_owner_until
  FROM public.admin_capability_grants AS g
  WHERE g.user_id = v_user_id AND g.capability = 'full_owner' AND g.expires_at > pg_catalog.now();
  RETURN jsonb_build_object(
    'is_admin', COALESCE(v_role IN ('owner','admin'), false),
    'is_owner', COALESCE(v_role = 'owner', false),
    'owner_authority_until', v_owner_until,
    'is_team_admin', EXISTS (
      SELECT 1 FROM public.team_admin_assignments AS a
      JOIN public.teams AS t ON t.id = a.team_id AND t.is_active
      JOIN auth.users AS u ON u.id = a.user_id
      WHERE a.user_id = v_user_id AND u.deleted_at IS NULL
        AND (u.banned_until IS NULL OR u.banned_until <= now())
    ),
    'role', v_role, 'email', v_email, 'permissions', COALESCE(v_permissions, '{}'::jsonb), 'teams', v_teams
  );
END;
$$;
REVOKE ALL ON FUNCTION public.get_admin_access() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_admin_access() TO authenticated;

-- 5) حالة القدرات للمشرف الحالي ------------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_capability_state()
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid UUID := auth.uid();
  v_role TEXT;
  v_items JSONB;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED'; END IF;
  SELECT a.role INTO v_role FROM public.admin_accounts AS a WHERE a.user_id = v_uid;
  IF v_role IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED'; END IF;

  SELECT COALESCE(pg_catalog.jsonb_object_agg(k.key, pg_catalog.jsonb_build_object(
    'capability', k.key,
    'allowed', public.user_has_capability(v_uid, k.key),
    'granted_until', (
      SELECT g.expires_at FROM public.admin_capability_grants AS g
      WHERE g.user_id = v_uid AND g.capability = k.key AND g.expires_at > pg_catalog.now()
      ORDER BY g.expires_at DESC LIMIT 1
    ),
    'request', (
      SELECT pg_catalog.jsonb_build_object(
        'id', r.id,
        'status', r.status,
        'note', r.note,
        'requested_at', r.requested_at,
        'decided_at', r.decided_at,
        'decided_note', r.decided_note,
        'duration_minutes', r.duration_minutes,
        'expires_at', r.expires_at
      )
      FROM public.admin_capability_requests AS r
      WHERE r.user_id = v_uid AND r.capability = k.key
      ORDER BY r.requested_at DESC LIMIT 1
    )
  )), '{}'::jsonb)
  INTO v_items
  FROM (SELECT unnest(ARRAY['full_owner','admin_accounts','admin_password_reset','strikes','app_usage']) AS key) AS k;

  RETURN pg_catalog.jsonb_build_object(
    'is_owner', v_role = 'owner',
    'capabilities', v_items,
    'pending_count', CASE WHEN v_role = 'owner' THEN (
      SELECT count(*)::INTEGER FROM public.admin_capability_requests AS r WHERE r.status = 'pending'
    ) ELSE 0 END
  );
END;
$$;
REVOKE ALL ON FUNCTION public.admin_capability_state() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_capability_state() TO authenticated;

-- 6) المشرف بيطلب صلاحية ------------------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_request_capability(p_capability TEXT, p_note TEXT DEFAULT NULL)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid UUID := auth.uid();
  v_role TEXT;
  v_note TEXT := NULLIF(pg_catalog.btrim(COALESCE(p_note, '')), '');
  v_id BIGINT;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED'; END IF;
  SELECT a.role INTO v_role FROM public.admin_accounts AS a WHERE a.user_id = v_uid;
  IF v_role IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED'; END IF;
  IF v_role = 'owner' THEN RAISE EXCEPTION 'OWNER_HAS_CAPABILITY'; END IF;
  IF NOT public.is_capability_key(p_capability) THEN RAISE EXCEPTION 'INVALID_CAPABILITY'; END IF;
  IF public.user_has_capability(v_uid, p_capability) THEN RAISE EXCEPTION 'CAPABILITY_ALREADY_GRANTED'; END IF;
  IF v_note IS NOT NULL AND pg_catalog.char_length(v_note) > 500 THEN RAISE EXCEPTION 'INVALID_NOTE'; END IF;

  SELECT r.id INTO v_id FROM public.admin_capability_requests AS r
  WHERE r.user_id = v_uid AND r.capability = p_capability AND r.status = 'pending';
  IF v_id IS NOT NULL THEN RAISE EXCEPTION 'REQUEST_ALREADY_PENDING'; END IF;

  INSERT INTO public.admin_capability_requests (user_id, capability, note)
  VALUES (v_uid, p_capability, v_note)
  RETURNING id INTO v_id;

  RETURN pg_catalog.jsonb_build_object('id', v_id, 'capability', p_capability, 'status', 'pending');
END;
$$;
REVOKE ALL ON FUNCTION public.admin_request_capability(TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_request_capability(TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_cancel_capability_request(p_request_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid UUID := auth.uid();
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED'; END IF;
  UPDATE public.admin_capability_requests AS r
  SET status = 'cancelled', decided_at = pg_catalog.now()
  WHERE r.id = p_request_id AND r.user_id = v_uid AND r.status = 'pending';
  RETURN FOUND;
END;
$$;
REVOKE ALL ON FUNCTION public.admin_cancel_capability_request(BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_cancel_capability_request(BIGINT) TO authenticated;

-- 7) صندوق المالك: الطلبات + المنح --------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_capability_inbox()
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid UUID := auth.uid();
  v_requests JSONB;
  v_grants JSONB;
BEGIN
  IF v_uid IS NULL OR NOT public.is_owner_role(v_uid) THEN
    RAISE EXCEPTION 'OWNER_ONLY: طلبات الصلاحيات بتظهر للمالك بس.';
  END IF;

  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
    'id', r.id,
    'user_id', r.user_id,
    'email', u.email,
    'capability', r.capability,
    'note', r.note,
    'status', r.status,
    'requested_at', r.requested_at,
    'decided_at', r.decided_at,
    'decided_note', r.decided_note,
    'duration_minutes', r.duration_minutes,
    'expires_at', r.expires_at
  ) ORDER BY r.requested_at DESC), '[]'::jsonb)
  INTO v_requests
  FROM public.admin_capability_requests AS r
  JOIN auth.users AS u ON u.id = r.user_id
  WHERE r.requested_at > pg_catalog.now() - INTERVAL '30 days';

  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
    'id', g.id,
    'user_id', g.user_id,
    'email', u.email,
    'capability', g.capability,
    'granted_at', g.granted_at,
    'expires_at', g.expires_at
  ) ORDER BY g.expires_at), '[]'::jsonb)
  INTO v_grants
  FROM public.admin_capability_grants AS g
  JOIN auth.users AS u ON u.id = g.user_id
  WHERE g.expires_at > pg_catalog.now();

  RETURN pg_catalog.jsonb_build_object('requests', v_requests, 'grants', v_grants);
END;
$$;
REVOKE ALL ON FUNCTION public.admin_capability_inbox() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_capability_inbox() TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_decide_capability_request(
  p_request_id BIGINT,
  p_approve BOOLEAN,
  p_minutes INTEGER DEFAULT 1440,
  p_note TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid UUID := auth.uid();
  v_request public.admin_capability_requests;
  v_minutes INTEGER;
  v_grant_id BIGINT;
  v_expires TIMESTAMPTZ;
BEGIN
  IF v_uid IS NULL OR NOT public.is_owner_role(v_uid) THEN
    RAISE EXCEPTION 'OWNER_ONLY: الموافقة على الصلاحيات للمالك بس.';
  END IF;
  IF p_request_id IS NULL OR p_approve IS NULL THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;

  SELECT * INTO v_request FROM public.admin_capability_requests AS r
  WHERE r.id = p_request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'REQUEST_NOT_FOUND'; END IF;
  IF v_request.status <> 'pending' THEN RAISE EXCEPTION 'REQUEST_NOT_PENDING'; END IF;

  IF p_approve THEN
    v_minutes := GREATEST(15, LEAST(COALESCE(p_minutes, 1440), 43200)); -- 15 دقيقة .. 30 يوم
    v_expires := pg_catalog.now() + (v_minutes || ' minutes')::INTERVAL;
    INSERT INTO public.admin_capability_grants (user_id, capability, request_id, granted_by, expires_at)
    VALUES (v_request.user_id, v_request.capability, v_request.id, v_uid, v_expires)
    RETURNING id INTO v_grant_id;
  END IF;

  UPDATE public.admin_capability_requests AS r
  SET status = CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
      decided_at = pg_catalog.now(),
      decided_by = v_uid,
      decided_note = NULLIF(pg_catalog.btrim(COALESCE(p_note, '')), ''),
      duration_minutes = CASE WHEN p_approve THEN v_minutes ELSE NULL END,
      expires_at = v_expires
  WHERE r.id = p_request_id;

  RETURN pg_catalog.jsonb_build_object(
    'id', p_request_id,
    'status', CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
    'grant_id', v_grant_id,
    'expires_at', v_expires
  );
END;
$$;
REVOKE ALL ON FUNCTION public.admin_decide_capability_request(BIGINT, BOOLEAN, INTEGER, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_decide_capability_request(BIGINT, BOOLEAN, INTEGER, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_revoke_capability_grant(p_grant_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid UUID := auth.uid();
