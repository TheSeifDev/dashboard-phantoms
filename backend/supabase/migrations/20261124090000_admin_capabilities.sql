-- Round 27 — صلاحيات المشرفين الكاملة + طلبات صلاحية مؤقتة بموافقة المالك.
--
-- الفكرة:
--   * المشرف بياخد كل صلاحيات الأقسام افتراضيًا (members/tasks/ranking/notes/
--     announcements/whatsapp/ai_assistant/web_projects/dashboard).
--   * الحاجات الحساسة اللي كانت للمالك بس بقت "قدرات" (capabilities): بتظهر
--     للمشرف مقفولة، ولو حاول يستخدمها بيبعت طلب للمالك، والمالك بيوافق بمدة
--     محددة (دقايق) وبعدها الصلاحية بتقفل لوحدها.
--   * قدرة `full_owner` بتفتح كل مسارات المالك المؤقتة (زي الحذف النهائي)
--     عن طريق توسيع public.is_owner() نفسها.
--   * تصفير كلمة مرور حساب مشرف بقى مسموح للمالك (كان بيرمي IDENTITY_CONFLICT).
BEGIN;

-- 1) طلبات الصلاحيات ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_capability_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  capability TEXT NOT NULL,
  note TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  requested_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.now(),
  decided_at TIMESTAMPTZ,
  decided_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  decided_note TEXT,
  duration_minutes INTEGER,
  expires_at TIMESTAMPTZ,
  CONSTRAINT admin_capability_requests_status_check
    CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS admin_capability_requests_one_pending
  ON public.admin_capability_requests (user_id, capability)
  WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS admin_capability_requests_status_idx
  ON public.admin_capability_requests (status, requested_at DESC);

-- 2) المنح المؤقتة ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_capability_grants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  capability TEXT NOT NULL,
  request_id BIGINT REFERENCES public.admin_capability_requests(id) ON DELETE SET NULL,
  granted_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  granted_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.now(),
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS admin_capability_grants_lookup_idx
  ON public.admin_capability_grants (user_id, capability, expires_at DESC);

ALTER TABLE public.admin_capability_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_capability_grants ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_capability_requests FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.admin_capability_grants FROM PUBLIC, anon, authenticated;

-- 3) مساعدات الصلاحيات --------------------------------------------------------
CREATE OR REPLACE FUNCTION public.is_capability_key(p_capability TEXT)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT COALESCE(p_capability, '') = ANY (ARRAY[
    'full_owner', 'admin_accounts', 'admin_password_reset', 'strikes', 'app_usage'
  ]);
$$;
REVOKE ALL ON FUNCTION public.is_capability_key(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_capability_key(TEXT) TO authenticated, service_role;

-- دور المالك الحقيقي (بدون أي منح مؤقتة) — بيستخدم في الموافقات بس.
CREATE OR REPLACE FUNCTION public.is_owner_role(p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.admin_accounts AS a
    WHERE a.user_id = p_user_id AND a.role = 'owner'
  );
$$;
REVOKE ALL ON FUNCTION public.is_owner_role(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_owner_role(UUID) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.user_has_capability(p_user_id UUID, p_capability TEXT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT CASE
    WHEN p_user_id IS NULL THEN false
    WHEN public.is_owner_role(p_user_id) THEN true
    ELSE EXISTS (
      SELECT 1 FROM public.admin_capability_grants AS g
      WHERE g.user_id = p_user_id
        AND g.capability = p_capability
        AND g.expires_at > pg_catalog.now()
    )
  END;
$$;
REVOKE ALL ON FUNCTION public.user_has_capability(UUID, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.user_has_capability(UUID, TEXT) TO authenticated, service_role;

